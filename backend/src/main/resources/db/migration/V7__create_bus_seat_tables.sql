CREATE TABLE IF NOT EXISTS bus_seats (
    id VARCHAR(36) PRIMARY KEY,
    service_id VARCHAR(36) NOT NULL,
    seat_number VARCHAR(10) NOT NULL,
    deck VARCHAR(10) DEFAULT 'LOWER', -- LOWER, UPPER
    row_index INT NOT NULL,
    col_index INT NOT NULL,
    seat_type VARCHAR(20) NOT NULL, -- SEATER, SLEEPER_L, SLEEPER_R
    price DECIMAL(10, 2) NOT NULL,
    status VARCHAR(20) DEFAULT 'AVAILABLE', -- AVAILABLE, BOOKED, RESERVED_LADIES, LOCKED
    lock_expires_at TIMESTAMP NULL,
    FOREIGN KEY (service_id) REFERENCES bus_services(id) ON DELETE CASCADE
);

